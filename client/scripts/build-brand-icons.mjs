// Regenerates client/src/design/library/brandPaths.generated.js from Simple Icons (CC0-1.0).
//
//   cd client && npm i --no-save simple-icons@16.31.0 && node scripts/build-brand-icons.mjs
//
// Only the SVG path data is copied (24×24 viewBox), for the brands the component
// library lists in src/design/library/tech.js. The file is imported lazily, so the
// ~170KB of paths never lands in the workspace chunk. Simple Icons drops brands on
// trademark requests (AWS, Azure, Oracle… are gone); those catalogue entries use a
// generic glyph instead, and this script fails loudly if a listed brand disappears.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { TECH } from '../src/design/library/tech.js';

const require = createRequire(import.meta.url);
const icons = require('simple-icons');
const bySlug = new Map(Object.values(icons).filter((icon) => icon?.slug).map((icon) => [icon.slug, icon]));

const paths = {};
const missing = [];
for (const entry of TECH) {
  if (!entry.brand) continue;
  const icon = bySlug.get(entry.brand);
  if (!icon) missing.push(entry.brand);
  else paths[entry.brand] = icon.path;
}
if (missing.length) {
  console.error(`Not in this Simple Icons version: ${missing.join(', ')} — give those entries a glyph instead.`);
  process.exit(1);
}

// The package does not export its package.json; find it beside the resolved entry.
let dir = dirname(require.resolve('simple-icons'));
while (!JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).name?.startsWith('simple-icons')) dir = dirname(dir);
const { version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
const body = Object.entries(paths)
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([slug, path]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(path)},`)
  .join('\n');
const out = new URL('../src/design/library/brandPaths.generated.js', import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/build-brand-icons.mjs from simple-icons@${version} (CC0-1.0). Do not edit.\n` +
    `// Brand names and logos are trademarks of their owners; shown here only to identify the technology.\n` +
    `export const BRAND_PATHS = {\n${body}\n};\n`,
);
console.log(`Wrote ${Object.keys(paths).length} brand paths.`);
