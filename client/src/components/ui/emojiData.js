/** One flat lookup, built once. Search reads this instead of nine arrays. */
export const ALL_EMOJI = EMOJI_GROUPS.flatMap((group) =>
  group.emoji.map(([char, keywords]) => ({ char, keywords, group: group.id })),
);

/** Everything the query could match: the words, the group name, the glyph. */
export function searchEmoji(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const words = q.split(/\s+/);
  return ALL_EMOJI.filter(({ char, keywords, group }) => {
    const hay = `${keywords} ${group}`;
    return words.every((w) => hay.includes(w) || char === w);
  });
}
