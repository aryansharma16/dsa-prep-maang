import assert from 'node:assert/strict';
import { test } from 'node:test';
import { analyzeDbml } from '../schema/analyze.js';
import { toDdl } from '../schema/ddl.js';
import { sqlToDbml } from '../schema/sqlImport.js';

const PG_DUMP = `
--
-- PostgreSQL database dump
--
SET statement_timeout = 0;
CREATE TYPE public.order_status AS ENUM ('pending', 'paid', 'on hold');

CREATE TABLE public.users (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email character varying(255) NOT NULL,
    display_name text DEFAULT 'friend'::text,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    tags text[],
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT email_shape CHECK ((email ~~ '%@%'::text))
);

CREATE TABLE orders (
    id bigserial PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status public.order_status DEFAULT 'pending' NOT NULL,
    total numeric(10,2) DEFAULT 0
);

CREATE TABLE "order lines" (
    order_id bigint,
    product_id integer,
    qty integer DEFAULT 1,
    PRIMARY KEY (order_id, product_id)
);

ALTER TABLE ONLY "order lines"
    ADD CONSTRAINT lines_order_fk FOREIGN KEY (order_id) REFERENCES public.orders(id) ON UPDATE CASCADE ON DELETE RESTRICT;

CREATE UNIQUE INDEX CONCURRENTLY IF NOT EXISTS orders_user_status ON public.orders USING btree (user_id, status);
CREATE INDEX users_lower_email ON users (lower(email));
COMMENT ON TABLE public.users IS 'People who can log in';
COMMENT ON COLUMN public.users.email IS 'Login, unique';
INSERT INTO users (email) VALUES ('a@b.c');
CREATE FUNCTION touch() RETURNS trigger AS $$ BEGIN RETURN NEW; END; $$ LANGUAGE plpgsql;
`;

const MYSQL_DUMP = `
/*!40101 SET NAMES utf8mb4 */;
CREATE TABLE IF NOT EXISTS \`customers\` (
  \`id\` int unsigned NOT NULL AUTO_INCREMENT,
  \`name\` varchar(100) NOT NULL COMMENT 'Full name',
  \`tier\` enum('free','pro','team') NOT NULL DEFAULT 'free',
  \`updated_at\` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (\`id\`),
  UNIQUE KEY \`uniq_name\` (\`name\`),
  KEY \`idx_tier\` (\`tier\`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Paying customers';

CREATE TABLE \`invoices\` (
  \`id\` bigint NOT NULL AUTO_INCREMENT PRIMARY KEY,
  \`customer_id\` int unsigned DEFAULT NULL,
  \`amount\` decimal(12,2) NOT NULL DEFAULT '0.00',
  CONSTRAINT \`fk_invoice_customer\` FOREIGN KEY (\`customer_id\`) REFERENCES \`customers\` (\`id\`) ON DELETE SET NULL
) ENGINE=InnoDB;
`;

test('imports a PostgreSQL dump into DBML that analyzes cleanly', () => {
  const { dbml, warnings } = sqlToDbml(PG_DUMP);
  const model = analyzeDbml(dbml);
  assert.deepEqual(model.diagnostics, [], `${dbml}\n${JSON.stringify(model.diagnostics)}`);
  assert.deepEqual(model.tables.map((t) => t.name), ['users', 'orders', 'order lines']);
  const users = model.byKey.get('public.users');
  const col = (t, n) => t.columns.find((c) => c.name === n);
  assert.deepEqual([col(users, 'id').pk, col(users, 'id').increment], [true, true]);
  assert.deepEqual([col(users, 'email').type.name, col(users, 'email').type.args, col(users, 'email').notNull], ['character varying', ['255'], true]);
  assert.equal(col(users, 'email').note, 'Login, unique');
  assert.deepEqual(col(users, 'display_name').default, { kind: 'string', value: 'friend' });
  assert.deepEqual(col(users, 'created_at').default, { kind: 'expr', value: 'now()' });
  assert.equal(col(users, 'created_at').type.name, 'timestamp with time zone');
  assert.equal(col(users, 'tags').type.array, true);
  assert.equal(users.note, 'People who can log in');
  assert.ok(users.indexes.some((i) => i.unique && i.columns[0].name === 'email'));
  assert.ok(users.indexes.some((i) => i.columns[0].expr === 'lower(email)'));

  const orders = model.byKey.get('public.orders');
  assert.deepEqual([col(orders, 'id').type.name, col(orders, 'id').increment, col(orders, 'id').pk], ['bigint', true, true]);
  assert.equal(col(orders, 'status').enum, 'public.order_status');
  assert.ok(orders.indexes.some((i) => i.unique && i.name === 'orders_user_status' && i.type === 'btree'));

  const lines = model.byKey.get('public.order lines');
  assert.ok(lines.indexes.some((i) => i.pk && i.columns.map((c) => c.name).join() === 'order_id,product_id'));

  const rel = (from) => model.relations.find((r) => r.from.table === from);
  assert.deepEqual([rel('public.orders').to.table, rel('public.orders').onDelete], ['public.users', 'cascade']);
  assert.deepEqual([rel('public.order lines').name, rel('public.order lines').onDelete, rel('public.order lines').onUpdate], ['lines_order_fk', 'restrict', 'cascade']);
  assert.ok(warnings.some((w) => w.includes('FUNCTION')), warnings.join(' | '));
  assert.ok(!warnings.some((w) => /INSERT|SET/.test(w)), 'routine statements are skipped silently');
});

test('imports a MySQL dump: backticks, AUTO_INCREMENT, inline enum, KEY, COMMENT, SET NULL', () => {
  const { dbml } = sqlToDbml(MYSQL_DUMP);
  const model = analyzeDbml(dbml);
  assert.deepEqual(model.diagnostics, [], dbml);
  const customers = model.byKey.get('public.customers');
  const col = (t, n) => t.columns.find((c) => c.name === n);
  assert.deepEqual([col(customers, 'id').pk, col(customers, 'id').increment, col(customers, 'id').notNull], [true, true, false]);
  assert.equal(col(customers, 'name').note, 'Full name');
  assert.equal(col(customers, 'tier').enum, 'public.customers_tier_enum');
  assert.deepEqual(model.enums.get('public.customers_tier_enum').values.map((v) => v.name), ['free', 'pro', 'team']);
  assert.equal(customers.note, 'Paying customers');
  assert.ok(customers.indexes.some((i) => i.unique && i.name === 'uniq_name'));
  assert.ok(customers.indexes.some((i) => i.name === 'idx_tier' && i.type === 'btree'));
  const invoices = model.byKey.get('public.invoices');
  assert.deepEqual(col(invoices, 'amount').default, { kind: 'string', value: '0.00' });
  assert.deepEqual([model.relations[0].name, model.relations[0].onDelete], ['fk_invoice_customer', 'set null']);
});

test('round trip: DBML → Postgres DDL → DBML keeps tables, keys, enums and relations', () => {
  const original = `Enum status { on off }
Table a {
  id int [pk, increment]
  name varchar(20) [not null, unique]
  s status [default: 'on']
}
Table b {
  id int [pk]
  a_id int [ref: > a.id]
}`;
  const back = analyzeDbml(sqlToDbml(toDdl(original, 'postgres')).dbml);
  assert.deepEqual(back.diagnostics, []);
  const a = back.byKey.get('public.a');
  assert.deepEqual(a.columns.map((c) => [c.name, c.pk, c.increment, c.notNull, c.unique]), [
    ['id', true, true, false, false],
    ['name', false, false, true, true],
    ['s', false, false, false, false],
  ]);
  assert.equal(a.columns[2].enum, 'public.status');
  assert.deepEqual(back.relations.map((r) => [r.from.table, r.from.columns, r.to.table, r.to.columns]), [['public.b', ['a_id'], 'public.a', ['id']]]);
});
