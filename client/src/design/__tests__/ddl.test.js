import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { test } from 'node:test';
import { toDdl } from '../schema/ddl.js';

const SHOP = `Project shop { database_type: 'PostgreSQL' }
Enum order_status { pending paid "on hold" }
Table users [note: 'people'] {
  id bigint [pk, increment]
  email varchar(255) [not null, unique, note: 'login']
  nickname varchar(40) [default: 'friend']
  active boolean [default: true]
  created_at timestamp [default: \`CURRENT_TIMESTAMP\`]
}
Table orders {
  id bigint [pk, increment]
  user_id bigint [not null, ref: > users.id]
  status order_status [not null, default: 'pending']
  total decimal(10,2) [default: 0]
  indexes {
    (user_id, status) [name: 'orders_user_status']
    total [unique]
  }
}
Table products {
  id int [pk]
  name text
}
Table order_lines {
  order_id bigint
  product_id int
  qty int [not null, default: 1]
  indexes {
    (order_id, product_id) [pk]
  }
}
Table tags {
  id int [pk]
}
Ref: order_lines.order_id > orders.id [delete: cascade]
Ref fk_product { order_lines.product_id > products.id }
Ref: products.id <> tags.id`;

test('PostgreSQL: enums, identity, composite keys, indexes, comments, FKs after tables, junction table', () => {
  const sql = toDdl(SHOP, 'postgres');
  assert.match(sql, /CREATE TYPE "order_status" AS ENUM \('pending', 'paid', 'on hold'\);/);
  assert.match(sql, /"id" bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(sql, /"email" varchar\(255\) NOT NULL UNIQUE/);
  assert.match(sql, /"nickname" varchar\(40\) DEFAULT 'friend'/);
  assert.match(sql, /"active" boolean DEFAULT TRUE/);
  assert.match(sql, /"created_at" timestamp DEFAULT CURRENT_TIMESTAMP/);
  assert.match(sql, /"status" "order_status" NOT NULL DEFAULT 'pending'/);
  assert.match(sql, /PRIMARY KEY \("order_id", "product_id"\)/);
  assert.match(sql, /CREATE INDEX "orders_user_status" ON "orders" \("user_id", "status"\);/);
  assert.match(sql, /CREATE UNIQUE INDEX "orders_total_idx" ON "orders" \("total"\);/);
  assert.match(sql, /COMMENT ON TABLE "users" IS 'people';/);
  assert.match(sql, /COMMENT ON COLUMN "users"."email" IS 'login';/);
  assert.match(sql, /ALTER TABLE "orders" ADD FOREIGN KEY \("user_id"\) REFERENCES "users" \("id"\);/);
  assert.match(sql, /ALTER TABLE "order_lines" ADD FOREIGN KEY \("order_id"\) REFERENCES "orders" \("id"\) ON DELETE CASCADE;/);
  assert.match(sql, /ALTER TABLE "order_lines" ADD CONSTRAINT "fk_product" FOREIGN KEY/);
  assert.match(sql, /CREATE TABLE "products_tags" \(\n  "products_id" int NOT NULL,\n  "tags_id" int NOT NULL,\n  PRIMARY KEY \("products_id", "tags_id"\)\n\);/);
  // Every CREATE TABLE comes before the first ALTER TABLE.
  assert.ok(sql.lastIndexOf('CREATE TABLE') < sql.indexOf('ALTER TABLE'));
});

test('MySQL: backticks, AUTO_INCREMENT, inline ENUM, COMMENT, expression defaults in parentheses', () => {
  const sql = toDdl(SHOP, 'mysql');
  assert.match(sql, /`id` bigint PRIMARY KEY AUTO_INCREMENT/);
  assert.match(sql, /`status` ENUM\('pending', 'paid', 'on hold'\) NOT NULL DEFAULT 'pending'/);
  assert.match(sql, /`email` varchar\(255\) NOT NULL UNIQUE COMMENT 'login'/);
  assert.match(sql, /DEFAULT \(CURRENT_TIMESTAMP\)/);
  assert.match(sql, /\) COMMENT='people';/);
  assert.doesNotMatch(sql, /CREATE TYPE/);
});

test('SQLite: the script runs in sql.js, enforces the enum and foreign keys', async () => {
  const require = createRequire(import.meta.url);
  const initSqlJs = require('sql.js');
  const SQL = await initSqlJs();
  const db = new SQL.Database();
  const sql = toDdl(SHOP, 'sqlite');
  assert.match(sql, /"id" INTEGER PRIMARY KEY AUTOINCREMENT/);
  assert.match(sql, /CHECK \("status" IN \('pending', 'paid', 'on hold'\)\)/);
  db.exec('PRAGMA foreign_keys = ON;');
  db.exec(sql);
  const tables = db.exec("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")[0].values.flat();
  assert.deepEqual(tables, ['order_lines', 'orders', 'products', 'products_tags', 'tags', 'users']);
  db.exec("INSERT INTO users (email) VALUES ('a@b.c')");
  db.exec("INSERT INTO orders (user_id, status, total) VALUES (1, 'paid', 10)");
  assert.throws(() => db.exec("INSERT INTO orders (user_id, status, total) VALUES (1, 'lost', 11)"), /CHECK/);
  assert.throws(() => db.exec("INSERT INTO orders (user_id, status, total) VALUES (999, 'paid', 12)"), /FOREIGN KEY/);
  db.close();
});
